async function stageSelectedPageContent(
  client,
  manifest,
  inputDirectory,
  buildMode,
  targetSourceUrl,
  targetSourceUrls = [],
) {
  const data = recordValue(manifest.data);
  const allPages = sourcePagePlan(Array.isArray(data.selectedPages) ? data.selectedPages : []);
  const coveragePages = sourcePagePlan(
    Array.isArray(data.pageCoverage) ? data.pageCoverage : (data.selectedPages ?? []),
  );
  const targetSourceUrlSet = new Set(targetSourceUrls);
  const outputPages =
    buildMode === 'homepage_test'
      ? allPages.filter((page) => page.outputPath === 'index.html').slice(0, 1)
      : buildMode === 'page_test'
        ? targetSourceUrlSet.size
          ? allPages.filter((page) => targetSourceUrlSet.has(page.sourceUrl))
          : allPages.filter((page) => page.sourceUrl === targetSourceUrl).slice(0, 1)
        : allPages;
  if (!outputPages.length) {
    throw new Error(
      buildMode === 'homepage_test'
        ? 'The approved Build Manifest does not contain a homepage source page.'
        : buildMode === 'page_test'
          ? 'The selected page is not part of this approved Build Manifest.'
          : 'The approved Build Manifest does not contain any selected source pages.',
    );
  }
  const outputUrls = new Set(outputPages.map((page) => page.sourceUrl));
  const contextPages = coveragePages.filter((page) => {
    if (page.disposition === 'exclude') return false;
    if (outputUrls.has(page.sourceUrl)) return true;
    if (page.disposition !== 'merge' || !page.targetSourceUrl) return false;
    return outputUrls.has(page.targetSourceUrl);
  });
  const { data: artifacts, error } = await client
    .from('artifacts')
    .select('storage_bucket, storage_path, metadata, content_type, byte_size')
    .eq('crawl_run_id', manifest.crawl_run_id)
    .eq('kind', 'content');
  if (error) throw new BuilderInputError('captured_content_lookup', error);

  const contentBySourceUrl = new Map();
  for (const artifact of artifacts ?? []) {
    const metadata = recordValue(artifact.metadata);
    if (typeof metadata.sourceUrl !== 'string') continue;
    try {
      contentBySourceUrl.set(normaliseSourceUrl(metadata.sourceUrl), artifact);
    } catch {
      // A malformed historic artifact cannot be used as an approved page source.
    }
  }

  const sourceDirectory = join(inputDirectory, 'source-pages');
  await mkdir(sourceDirectory, { recursive: true });
  const stagedPages = [];
  for (const page of contextPages) {
    const artifact = contentBySourceUrl.get(page.sourceUrl);
    if (!artifact) {
      throw new Error(
        `The selected source page ${page.sourceUrl} has no captured content available for the builder.`,
      );
    }
    if (Number(artifact.byte_size) > maxSourceContentBytes) {
      throw new Error(
        `The captured content for ${page.sourceUrl} exceeds the private builder input limit.`,
      );
    }
    let blob;
    let downloadError;
    try {
      const result = await client.storage
        .from(artifact.storage_bucket || artifactBucket)
        .download(artifact.storage_path);
      blob = result.data;
      downloadError = result.error;
    } catch (error) {
      throw new BuilderInputError('captured_content_download', error, page.sourceUrl);
    }
    if (downloadError) {
      throw new BuilderInputError('captured_content_download', downloadError, page.sourceUrl);
    }
    if (!blob || blob.size > maxSourceContentBytes) {
      throw new Error(`The captured content for ${page.sourceUrl} could not be staged privately.`);
    }
    const content = Buffer.from(await blob.arrayBuffer());
    try {
      JSON.parse(content.toString('utf8'));
    } catch {
      throw new Error(
        `The captured content for ${page.sourceUrl} is not valid private source data.`,
      );
    }
    const contentFile = `${String(page.index).padStart(3, '0')}.json`;
    await writeFile(join(sourceDirectory, contentFile), content);
    await chmod(join(sourceDirectory, contentFile), 0o444);
    stagedPages.push({
      ...page,
      contentFile: `source-pages/${contentFile}`,
      contentBytes: content.byteLength,
    });
  }
  const indexPath = join(sourceDirectory, 'index.json');
  await writeFile(
    indexPath,
    JSON.stringify(
      {
        purpose:
          'Reviewed source-page content for a private redesign. Follow each disposition: only outputRequired pages become routes; merge sources contribute to their target; excluded sources are not staged.',
        pages: stagedPages,
      },
      null,
      2,
    ),
  );
  await chmod(indexPath, 0o444);
  const stagedByUrl = new Map(stagedPages.map((page) => [page.sourceUrl, page]));
  return outputPages.map((page) => stagedByUrl.get(page.sourceUrl) ?? page);
}

function selectedSourcePages(manifest, buildMode, targetSourceUrl, targetSourceUrls = []) {
  const data = recordValue(manifest.data);
  const allPages = sourcePagePlan(Array.isArray(data.selectedPages) ? data.selectedPages : []);
  const targetSourceUrlSet = new Set(targetSourceUrls);
  const pages =
    buildMode === 'homepage_test'
      ? allPages.filter((page) => page.outputPath === 'index.html').slice(0, 1)
      : buildMode === 'page_test'
        ? targetSourceUrlSet.size
          ? allPages.filter((page) => targetSourceUrlSet.has(page.sourceUrl))
          : allPages.filter((page) => page.sourceUrl === targetSourceUrl).slice(0, 1)
        : allPages;
  if (!pages.length) {
    throw new Error(
      buildMode === 'homepage_test'
        ? 'The approved Build Manifest does not contain a homepage source page.'
        : buildMode === 'page_test'
          ? 'The selected page is not part of this approved Build Manifest.'
          : 'The approved Build Manifest does not contain any selected source pages.',
    );
  }
  return pages;
}

function sourceBoundItemMatches(item, selectedPageUrls) {
  const value = recordValue(item);
  const candidate = value.sourcePageUrl ?? value.sourceUrl ?? value.url;
  if (typeof candidate !== 'string' || !candidate) return true;
  try {
    return selectedPageUrls.has(normaliseSourceUrl(candidate));
  } catch {
    return false;
  }
}

