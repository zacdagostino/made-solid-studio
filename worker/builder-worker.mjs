function createBuilderHeartbeat(client, run, workerId) {
  let stopped = false;
  let heartbeatInFlight = false;
  const renew = async () => {
    if (stopped || heartbeatInFlight) return;
    heartbeatInFlight = true;
    try {
      await heartbeatBuilderWorker(client, workerId, run.id);
    } catch (error) {
      console.error(
        '[builder-worker] heartbeat failed',
        run.id,
        error instanceof Error ? error.message : error,
      );
    } finally {
      heartbeatInFlight = false;
    }
  };
  const timer = setInterval(() => void renew(), builderHeartbeatIntervalMs);
  return {
    renew,
    stop() {
      stopped = true;
      clearInterval(timer);
    },
  };
}

async function runCommand(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const startedAt = Date.now();
    const child = spawn(command, args, {
      cwd: options.cwd,
      env: options.env,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk) => {
      stdout += chunk.toString();
    });
    child.stderr.on('data', (chunk) => {
      stderr += chunk.toString();
    });
    child.once('error', reject);
    child.once('exit', (code, signal) => {
      const result = { stdout, stderr, code, signal, durationMs: Date.now() - startedAt };
      if (code === 0) return resolve(result);
      const error = new Error(
        `${command} ${signal ? `stopped (${signal})` : `exited with ${code}`}: ${stderr.slice(-800)}`,
      );
      error.commandResult = result;
      reject(error);
    });
  });
}

async function runDiagnosticCommand(diagnostics, scope, command, args, options = {}) {
  const commandText = [command, ...args].join(' ');
  try {
    const result = await runCommand(command, args, options);
    await diagnostics.record({
      scope,
      title: `${command} completed`,
      command: commandText,
      stdout: result.stdout,
      stderr: result.stderr,
      durationMs: result.durationMs,
    });
    return result;
  } catch (error) {
    const result = error?.commandResult ?? {};
    await diagnostics.record({
      scope,
      title: `${command} failed`,
      status: 'failed',
      detail:
        error instanceof Error ? error.message : 'The command failed without an error message.',
      command: commandText,
      stdout: result.stdout,
      stderr: result.stderr,
      durationMs: result.durationMs,
    });
    throw error;
  }
}

async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === '.git' || entry.name === 'node_modules') continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(path)));
    if (entry.isFile()) files.push(path);
  }
  return files;
}

async function collectBrowsableSourceFiles(directory, relativeDirectory = '') {
  const entries = await readdir(join(directory, relativeDirectory), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativePath = [relativeDirectory, entry.name].filter(Boolean).join('/');
    if (
      entry.name === '.env' ||
      entry.name.startsWith('.env.') ||
      entry.name === '.npmrc' ||
      entry.name.endsWith('.log') ||
      entry.name.endsWith('.tsbuildinfo')
    ) {
      continue;
    }
    if (
      entry.isDirectory() &&
      (entry.name === '.git' ||
        entry.name === '.next' ||
        entry.name === 'node_modules' ||
        relativePath === 'out' ||
        relativePath === 'public/assets')
    ) {
      continue;
    }
    if (entry.isDirectory()) {
      files.push(...(await collectBrowsableSourceFiles(directory, relativePath)));
    }
    if (entry.isFile()) files.push(join(directory, relativePath));
  }
  return files;
}

function wait(milliseconds) {
  return new Promise((resolve) => setTimeout(resolve, milliseconds));
}

function fetchWithRequestTimeout(
  input,
  init = {},
  timeoutMs = builderRequestTimeoutMs,
  fetchImplementation = globalThis.fetch,
) {
  const timeoutSignal = AbortSignal.timeout(timeoutMs);
  const signal = init.signal ? AbortSignal.any([init.signal, timeoutSignal]) : timeoutSignal;
  return fetchImplementation(input, { ...init, signal });
}

async function uploadArtifact(client, run, artifact) {
  const storagePath = `${run.organization_id}/builder-runs/${run.id}/${artifact.relativePath}`;
  let failure;
  const attempts = 3;
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    try {
      const { error: uploadError } = await client.storage
        .from(artifactBucket)
        .upload(storagePath, artifact.body, {
          contentType: artifact.contentType,
          upsert: true,
        });
      if (uploadError) {
        failure = new BuilderStorageError('storage_upload', artifact, uploadError, attempt);
      } else {
        const { error: recordError } = await client.from('builder_artifacts').upsert(
          {
            organization_id: run.organization_id,
            business_id: run.business_id,
            builder_run_id: run.id,
            kind: artifact.kind,
            label: artifact.label,
            storage_bucket: artifactBucket,
            storage_path: storagePath,
            content_type: artifact.contentType,
            byte_size: artifact.body.byteLength,
            metadata: artifact.metadata ?? {},
          },
          { onConflict: 'storage_path' },
        );
        if (!recordError) return storagePath;
        failure = new BuilderStorageError('artifact_index', artifact, recordError, attempt);
      }
    } catch (error) {
      failure =
        error instanceof BuilderStorageError
          ? error
          : new BuilderStorageError('storage_upload', artifact, error, attempt);
    }
    if (!failure?.retryable) throw failure;
    if (attempt < attempts) await wait(400 * 2 ** (attempt - 1));
  }
  throw failure;
}

function createEventWriter(client, run) {
  let nextSequence;
  let queue = Promise.resolve();
  return (kind, message, metadata = {}) => {
    queue = queue
      .then(async () => {
        if (!nextSequence) {
          const { data } = await client
            .from('builder_events')
            .select('sequence')
            .eq('builder_run_id', run.id)
            .order('sequence', { ascending: false })
            .limit(1);
          nextSequence = (data?.[0]?.sequence ?? 0) + 1;
        }
        const { error } = await client.from('builder_events').insert({
          organization_id: run.organization_id,
          business_id: run.business_id,
          builder_run_id: run.id,
          sequence: nextSequence,
          kind,
          message,
          metadata,
        });
        if (!error) nextSequence += 1;
      })
      .catch(() => {
        // Progress events must never prevent a private build from completing.
      });
    return queue;
  };
}

function textFromCodexItem(item) {
  const candidates = [item.text, item.message, item.content];
  for (const candidate of candidates) {
    if (typeof candidate === 'string' && candidate.trim()) return candidate.trim();
    if (Array.isArray(candidate)) {
      const text = candidate
        .map((part) => (typeof part?.text === 'string' ? part.text : ''))
        .filter(Boolean)
        .join(' ')
        .trim();
      if (text) return text;
    }
  }
  return '';
}

function codexItemField(item, keys) {
  for (const key of keys) {
    const value = item[key];
    if (typeof value === 'string' && value.trim()) return value;
    if (typeof value === 'number') return String(value);
  }
  return undefined;
}

function safeCodexStreamText(value) {
  return value
    .replace(/\b(?:sk|sk-proj|sk-[a-z]+)-[a-zA-Z0-9_-]{12,}\b/g, '[redacted key]')
    .replace(/\bBearer\s+[a-zA-Z0-9._~-]+/gi, 'Bearer [redacted]')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 900);
}

async function sourceFileHashes(siteDirectory) {
  const sourceDirectory = join(siteDirectory, 'src');
  const files = await collectFiles(sourceDirectory).catch(() => []);
  const hashes = new Map();
  for (const file of files) {
    const relativePath = relative(sourceDirectory, file).split(sep).join('/');
    hashes.set(relativePath, sha256(await readFile(file)));
  }
  return hashes;
}

function checkpointableSourcePath(relativePath) {
  if (
    typeof relativePath !== 'string' ||
    !relativePath ||
    relativePath.length > 240 ||
    relativePath.startsWith('/') ||
    relativePath.includes('\\') ||
    relativePath.startsWith('assets/')
  ) {
    return false;
  }
  return relativePath.split('/').every((part) => part && part !== '.' && part !== '..');
}

function hasSourceChanges(currentFiles, initialSourceHashes) {
  const checkpointFiles = currentFiles.filter((file) =>
    checkpointableSourcePath(file.relativePath),
  );
  if (
    checkpointFiles.length !==
    [...initialSourceHashes.keys()].filter(checkpointableSourcePath).length
  ) {
    return true;
  }
  return checkpointFiles.some((file) => initialSourceHashes.get(file.relativePath) !== file.hash);
}

function sourceCheckpointPayload(currentFiles, templateSourceHashes) {
  return {
    version: 1,
    generatedAt: new Date().toISOString(),
    files: currentFiles
      .filter((file) => checkpointableSourcePath(file.relativePath))
      .map((file) => ({
        path: file.relativePath,
        hash: file.hash,
        source:
          templateSourceHashes.get(file.relativePath) === file.hash ? 'template' : 'checkpoint',
      }))
      .sort((left, right) => left.path.localeCompare(right.path)),
  };
}

async function checkpointSourceBody(client, sourceRun, path, entry) {
  const sourceStoragePaths = [
    `${sourceRun.organization_id}/builder-runs/${sourceRun.id}/draft-source/${entry.hash}/${path}`,
    `${sourceRun.organization_id}/builder-runs/${sourceRun.id}/draft-source/${path}`,
    `${sourceRun.organization_id}/builder-runs/${sourceRun.id}/draft/${path}`,
  ];
  let sourceBlob;
  let sourceError;
  for (const storagePath of sourceStoragePaths) {
    const result = await client.storage.from(artifactBucket).download(storagePath);
    sourceBlob = result.data;
    sourceError = result.error;
    if (!sourceError && sourceBlob) break;
  }
  if (!sourceError && sourceBlob && sourceBlob.size <= 5_000_000) {
    const body = Buffer.from(await sourceBlob.arrayBuffer());
    if (sha256(body) === entry.hash) return body;
  }

  // Older runs overwrote a stable draft object key. The storage CDN can retain the
  // first object at that key even though the checkpoint records the later source
  // hash. Completed runs also save the same generated source as an immutable
  // site_file, so use that only when it satisfies the checkpoint's exact hash.
  const { data: generatedFiles, error: generatedFileError } = await client
    .from('builder_artifacts')
    .select('storage_bucket, storage_path')
    .eq('builder_run_id', sourceRun.id)
    .eq('kind', 'site_file')
    .eq('label', path)
    .order('created_at', { ascending: false })
    .limit(1);
  if (generatedFileError) {
    throw new BuilderCheckpointError('The checkpoint fallback record could not be read.', {
      retryable: true,
      context: { operation: 'checkpoint_fallback_lookup', path: `site/${path}` },
    });
  }
  const generatedFile = generatedFiles?.[0];
  if (generatedFile) {
    const { data: generatedBlob, error: generatedError } = await client.storage
      .from(generatedFile.storage_bucket || artifactBucket)
      .download(generatedFile.storage_path);
    if (!generatedError && generatedBlob && generatedBlob.size <= 5_000_000) {
      const generatedBody = Buffer.from(await generatedBlob.arrayBuffer());
      if (sha256(generatedBody) === entry.hash) return generatedBody;
    }
  }

  if (sourceError || !sourceBlob) {
    throw new BuilderCheckpointError('A private checkpoint source file could not be loaded.', {
      retryable: true,
      context: { operation: 'checkpoint_source_download', path: `draft-source/${path}` },
    });
  }
  if (sourceBlob.size > 5_000_000) {
    throw new BuilderCheckpointError(
      'A private checkpoint source file exceeded the safe size limit.',
      {
        context: { operation: 'checkpoint_source_validation', path: `draft-source/${path}` },
      },
    );
  }
  throw new BuilderCheckpointError(
    'A private checkpoint source file failed integrity validation.',
    {
      context: { operation: 'checkpoint_source_validation', path: `draft-source/${path}` },
    },
  );
}

async function restoreCheckpointFile(client, sourceRun, sourceDirectory, path, entry) {
  const destination = join(sourceDirectory, path);
  if (entry.source === 'template') {
    const existingBody = await readFile(destination).catch(() => undefined);
    if (existingBody && sha256(existingBody) === entry.hash) return false;
  }
  const body = await checkpointSourceBody(client, sourceRun, path, entry);
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, body);
  return true;
}

async function restoreSourceCheckpoint(client, run, sourceDirectory, sourceRun = run) {
  const { data: checkpoints, error: checkpointError } = await client
    .from('builder_artifacts')
    .select('storage_bucket, storage_path, metadata')
    .eq('builder_run_id', sourceRun.id)
    .eq('kind', 'checkpoint')
    .eq('label', 'Latest private source checkpoint')
    .order('created_at', { ascending: false })
    .limit(1);
  if (checkpointError) {
    throw new BuilderCheckpointError('The private checkpoint record could not be read.', {
      retryable: true,
      context: { operation: 'checkpoint_lookup' },
    });
  }
  const checkpoint = checkpoints?.[0];
  if (!checkpoint) return restoreLegacyDraftFiles(client, sourceRun, sourceDirectory);

  const { data: checkpointBlob, error: downloadError } = await client.storage
    .from(checkpoint.storage_bucket || artifactBucket)
    .download(checkpoint.storage_path);
  if (downloadError || !checkpointBlob) {
    throw new BuilderCheckpointError('The private checkpoint manifest could not be loaded.', {
      retryable: true,
      context: {
        operation: 'checkpoint_manifest_download',
        path: 'checkpoint/source-manifest.json',
      },
    });
  }
  if (checkpointBlob.size > 512_000) {
    throw new BuilderCheckpointError(
      'The private checkpoint manifest exceeded the safe size limit.',
      {
        context: {
          operation: 'checkpoint_manifest_validation',
          path: 'checkpoint/source-manifest.json',
        },
      },
    );
  }

  let payload;
  try {
    payload = JSON.parse(await checkpointBlob.text());
  } catch {
    throw new BuilderCheckpointError('The private checkpoint manifest was not valid JSON.', {
      context: {
        operation: 'checkpoint_manifest_validation',
        path: 'checkpoint/source-manifest.json',
      },
    });
  }
  const files = Array.isArray(payload?.files) ? payload.files : undefined;
  if (payload?.version !== 1 || !files || files.length > 300) {
    throw new BuilderCheckpointError('The private checkpoint manifest had an unsupported shape.', {
      context: {
        operation: 'checkpoint_manifest_validation',
        path: 'checkpoint/source-manifest.json',
      },
    });
  }
  const recordedFileCount = Number(recordValue(checkpoint.metadata).fileCount);
  if (
    Number.isFinite(recordedFileCount) &&
    recordedFileCount > 0 &&
    files.length !== recordedFileCount
  ) {
    const immutableDraftRestore = await restoreLegacyDraftFiles(client, sourceRun, sourceDirectory);
    if (immutableDraftRestore.restored) {
      return {
        ...immutableDraftRestore,
        restoredFromLegacyDrafts: false,
        checkpointState: recordValue(checkpoint.metadata).state,
      };
    }
    throw new BuilderCheckpointError(
      'The private checkpoint manifest did not match its recorded source file count.',
      {
        context: {
          operation: 'checkpoint_manifest_validation',
          recordedFileCount,
          manifestFileCount: files.length,
        },
      },
    );
  }

  const expectedFiles = new Map();
  for (const entry of files) {
    const path = typeof entry?.path === 'string' ? entry.path : '';
    const hash = typeof entry?.hash === 'string' ? entry.hash : '';
    const source = entry?.source;
    if (
      !checkpointableSourcePath(path) ||
      !/^[a-f0-9]{64}$/i.test(hash) ||
      (source !== 'template' && source !== 'checkpoint') ||
      expectedFiles.has(path)
    ) {
      throw new BuilderCheckpointError('The private checkpoint manifest included an unsafe file.', {
        context: { operation: 'checkpoint_manifest_validation', path },
      });
    }
    expectedFiles.set(path, { hash, source });
  }

  const existingFiles = await collectFiles(sourceDirectory).catch(() => []);
  for (const file of existingFiles) {
    const path = relative(sourceDirectory, file).split(sep).join('/');
    if (checkpointableSourcePath(path) && !expectedFiles.has(path)) {
      await rm(file, { force: true });
    }
  }

  const draftHashes = new Map();
  for (const [path, entry] of expectedFiles) {
    const restored = await restoreCheckpointFile(client, sourceRun, sourceDirectory, path, entry);
    if (restored) draftHashes.set(path, entry.hash);
  }

  return {
    restored: true,
    restoredFromLegacyDrafts: false,
    draftHashes,
    checkpointHash: sha256(JSON.stringify({ version: payload.version, files })),
    checkpointState: recordValue(checkpoint.metadata).state,
    fileCount: expectedFiles.size,
  };
}

async function refreshLockedFoundation(siteDirectory) {
  await Promise.all(
    lockedFoundationPaths.map(async (relativePath) => {
      const source = join(templateDirectory, relativePath);
      const destination = join(siteDirectory, relativePath);
      await mkdir(dirname(destination), { recursive: true });
      await chmod(destination, 0o644).catch(() => undefined);
      await cp(source, destination, { force: true });
    }),
  );
}

async function restoreLegacyDraftFiles(client, run, sourceDirectory) {
  const { data: artifacts, error } = await client
    .from('builder_artifacts')
    .select('label, storage_bucket, storage_path, created_at, metadata')
    .eq('builder_run_id', run.id)
    .eq('kind', 'draft_file')
    .order('created_at', { ascending: false });
  if (error) {
    throw new BuilderCheckpointError('The saved private draft records could not be read.', {
      retryable: true,
      context: { operation: 'legacy_draft_lookup' },
    });
  }
  const seenPaths = new Set();
  const drafts = (artifacts ?? []).filter((artifact) => {
    if (
      recordValue(artifact.metadata).state === 'compiled_working_draft' ||
      !checkpointableSourcePath(artifact.label) ||
      seenPaths.has(artifact.label)
    ) {
      return false;
    }
    seenPaths.add(artifact.label);
    return true;
  });
  if (!drafts.length) {
    return {
      restored: false,
      restoredFromLegacyDrafts: false,
      draftHashes: new Map(),
      checkpointHash: undefined,
    };
  }

  const draftHashes = new Map();
  for (const artifact of drafts) {
    const { data: sourceBlob, error: sourceError } = await client.storage
      .from(artifact.storage_bucket || artifactBucket)
      .download(artifact.storage_path);
    if (sourceError || !sourceBlob) {
      throw new BuilderCheckpointError('A saved private draft file could not be restored.', {
        retryable: true,
        context: { operation: 'legacy_draft_download', path: artifact.label },
      });
    }
    if (sourceBlob.size > 5_000_000) {
      throw new BuilderCheckpointError('A saved private draft file exceeded the safe size limit.', {
        context: { operation: 'legacy_draft_validation', path: artifact.label },
      });
    }
    const body = Buffer.from(await sourceBlob.arrayBuffer());
    const destination = join(sourceDirectory, artifact.label);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, body);
    draftHashes.set(artifact.label, sha256(body));
  }
  return {
    restored: true,
    restoredFromLegacyDrafts: true,
    draftHashes,
    checkpointHash: undefined,
    fileCount: drafts.length,
  };
}

async function saveSourceCheckpoint(client, run, workspace, currentFiles, event, options = {}) {
  const payload = sourceCheckpointPayload(currentFiles, workspace.templateSourceHashes);
  const body = Buffer.from(JSON.stringify(payload));
  const hash = sha256(JSON.stringify({ version: payload.version, files: payload.files }));
  const checkpointState = options.state ?? 'resume_checkpoint';
  if (
    workspace.checkpointHash === hash &&
    (workspace.checkpointState === checkpointState ||
      workspace.checkpointState === 'post_codex_validated')
  ) {
    return true;
  }
  try {
    await uploadArtifact(client, run, {
      kind: 'checkpoint',
      label: 'Latest private source checkpoint',
      relativePath: `checkpoint/${hash}/source-manifest.json`,
      body,
      contentType: 'application/json',
      metadata: {
        version: payload.version,
        fileCount: payload.files.length,
        state: checkpointState,
      },
    });
    workspace.checkpointHash = hash;
    workspace.checkpointState = checkpointState;
    workspace.checkpointFailure = undefined;
    await event(
      'stage',
      options.validated
        ? `Validated post-Codex source checkpoint saved with ${payload.files.length} file${payload.files.length === 1 ? '' : 's'}.`
        : `Private source checkpoint saved with ${payload.files.length} file${payload.files.length === 1 ? '' : 's'}.`,
      {
        fileCount: payload.files.length,
        checkpointState,
      },
    );
    return true;
  } catch (error) {
    const context = error instanceof BuilderStorageError ? error.context : {};
    const fingerprint = JSON.stringify(context);
    if (workspace.checkpointFailure !== fingerprint) {
      workspace.checkpointFailure = fingerprint;
      await event(
        'activity',
        'The private source checkpoint could not be saved yet. The website build will continue and retry the checkpoint.',
        { path: 'checkpoint/source-manifest.json', ...context },
      );
    }
    return false;
  }
}

async function syncDraftFiles(client, run, workspace, event, options = {}) {
  const sourceDirectory = join(workspace.siteDirectory, 'src');
  const files = await collectFiles(sourceDirectory).catch(() => []);
  const currentFiles = [];
  for (const file of files) {
    const relativePath = relative(sourceDirectory, file).split(sep).join('/');
    if (relativePath === '.gitkeep') continue;
    const body = await readFile(file);
    const hash = sha256(body);
    currentFiles.push({ file, relativePath, body, hash });
  }
  const sourceChanged = hasSourceChanges(currentFiles, workspace.initialSourceHashes);
  if (!workspace.draftPublished && !sourceChanged && !options.force) return false;
  for (const current of currentFiles) {
    const initialHash = workspace.initialSourceHashes.get(current.relativePath);
    const needsDraftArtifact =
      checkpointableSourcePath(current.relativePath) &&
      (options.force ||
        initialHash !== current.hash ||
        workspace.draftHashes.has(current.relativePath));
    if (!needsDraftArtifact) continue;
    if (workspace.draftHashes.get(current.relativePath) === current.hash) continue;
    try {
      await uploadArtifact(client, run, {
        kind: 'draft_file',
        label: current.relativePath,
        relativePath: `draft-source/${current.hash}/${current.relativePath}`,
        body: current.body,
        contentType: contentTypeFor(current.file),
        metadata: {
          sourcePath: current.relativePath,
          sourceHash: current.hash,
          state: 'working_source',
        },
      });
      workspace.draftHashes.set(current.relativePath, current.hash);
      workspace.draftFailures.delete(current.relativePath);
      await event('file', `Draft file updated: ${current.relativePath}`, {
        path: current.relativePath,
      });
    } catch (error) {
      const context = error instanceof BuilderStorageError ? error.context : {};
      const fingerprint = JSON.stringify(context);
      if (workspace.draftFailures.get(current.relativePath) !== fingerprint) {
        workspace.draftFailures.set(current.relativePath, fingerprint);
        await event(
          'activity',
          `Draft file could not be saved yet: ${current.relativePath}. The website build will continue and retry the draft sync.`,
          { path: current.relativePath, ...context },
        );
      }
    }
  }
  const hasUnsavedSourceFiles = currentFiles.some(
    (current) =>
      checkpointableSourcePath(current.relativePath) &&
      (options.force || workspace.initialSourceHashes.get(current.relativePath) !== current.hash) &&
      workspace.draftHashes.get(current.relativePath) !== current.hash,
  );
  if (!hasUnsavedSourceFiles && sourceChanged) {
    await saveSourceCheckpoint(client, run, workspace, currentFiles, event, {
      state: options.checkpointState,
      validated: options.checkpointState === 'post_codex_validated',
    });
  }
  return workspace.draftPublished;
}

async function syncDraftOutputFiles(client, run, workspace, event) {
  const outputDirectory = join(workspace.siteDirectory, compiledOutputDirectoryName);
  const requiredOutputPaths = requiredCompiledOutputPaths(workspace);
  const entryOutputPath = requiredOutputPaths[0];
  let entryDocument;
  try {
    entryDocument = await readFile(join(outputDirectory, entryOutputPath), 'utf8');
  } catch {
    return false;
  }
  if (isLockedStarterDocument(entryDocument)) return false;
  const files = await collectFiles(outputDirectory).catch(() => []);
  for (const file of files) {
    if (isPlaceholderOutputFile(file)) continue;
    const relativePath = relative(outputDirectory, file).split(sep).join('/');
    const body = await readFile(file);
    const hash = sha256(body);
    if (workspace.draftOutputHashes.get(relativePath) === hash) continue;
    await uploadArtifact(client, run, {
      kind: 'draft_file',
      label: relativePath,
      relativePath: `draft/${relativePath}`,
      body,
      contentType: contentTypeFor(file),
      metadata: {
        previewPath: relativePath,
        state: 'compiled_working_draft',
      },
    });
    workspace.draftOutputHashes.set(relativePath, hash);
  }
  workspace.draftPublished = requiredOutputPaths.every((outputPath) =>
    workspace.draftOutputHashes.has(outputPath),
  );
  if (workspace.draftPublished) {
    await event('activity', 'Compiled private working draft updated.', {
      fileCount: workspace.draftOutputHashes.size,
    });
  }
  return workspace.draftPublished;
}

function sourceUrlSet(pages) {
  return new Set(
    pages
      .map((page) => page?.sourceUrl ?? page?.url)
      .filter((value) => typeof value === 'string')
      .map((value) => {
        try {
          return normaliseSourceUrl(value);
        } catch {
          return undefined;
        }
      })
      .filter(Boolean),
  );
}

function assetMatchesSelectedPages(asset, selectedPageUrls, primaryLogoAssetId) {
  if (!selectedPageUrls.size) return true;
  const metadata = recordValue(asset.metadata);
  if (
    asset.id === primaryLogoAssetId ||
    metadata.derivedFromAssetId === primaryLogoAssetId ||
    metadata.logoVariant === 'appearance' ||
    metadata.logoVariant === 'editable'
  ) {
    return true;
  }
  const pageUrls = [
    metadata.pageUrl,
    ...(Array.isArray(metadata.pageUrls) ? metadata.pageUrls : []),
  ].filter((value) => typeof value === 'string');
  if (!pageUrls.length) return true;
  return pageUrls.some((value) => {
    try {
      return selectedPageUrls.has(normaliseSourceUrl(value));
    } catch {
      return false;
    }
  });
}

function groupApprovedAssetsByContent(assets, primaryLogoAssetId = '') {
  const contentGroups = new Map();
  for (const asset of assets) {
    const key =
      typeof asset.sha256 === 'string' && asset.sha256 ? asset.sha256 : `asset:${asset.id}`;
    const existing = contentGroups.get(key);
    if (!existing) {
      contentGroups.set(key, { asset, assets: [asset] });
    } else {
      existing.assets.push(asset);
      if (asset.id === primaryLogoAssetId) existing.asset = asset;
    }
  }
  return [...contentGroups.values()];
}

async function stageApprovedAssets(client, manifest, siteDirectory, selectedPages = []) {
  const data = recordValue(manifest.data);
  const brandKit = recordValue(data.brandKit);
  const guidanceByAssetId = new Map(
    (Array.isArray(data.approvedAssetGuidance) ? data.approvedAssetGuidance : [])
      .map((item) => recordValue(item))
      .filter((item) => typeof item.assetId === 'string')
      .map((item) => [item.assetId, item]),
  );
  const recoveredContentAssetIds = new Set(
    (Array.isArray(data.approvedVisualContent) ? data.approvedVisualContent : [])
      .map((item) => recordValue(item).assetId)
      .filter((id) => typeof id === 'string'),
  );
  const primaryLogoAssetId =
    typeof brandKit.primaryLogoAssetId === 'string' ? brandKit.primaryLogoAssetId : '';
  const assetIds = new Set(
    Array.isArray(data.approvedAssetGuidance)
      ? data.approvedAssetGuidance
          .map((asset) => recordValue(asset).assetId)
          .filter((id) => typeof id === 'string')
      : [],
  );
  if (typeof brandKit.primaryLogoAssetId === 'string') assetIds.add(brandKit.primaryLogoAssetId);
  if (Array.isArray(brandKit.approvedAssetIds)) {
    for (const assetId of brandKit.approvedAssetIds) {
      if (typeof assetId === 'string') assetIds.add(assetId);
    }
  }
  for (const recoveredAssetId of recoveredContentAssetIds) {
    assetIds.delete(recoveredAssetId);
  }
  const assetsDirectory = join(siteDirectory, 'public', 'assets');
  await rm(assetsDirectory, { recursive: true, force: true });
  if (!assetIds.size) return [];
  const { data: assets, error } = await client
    .from('artifacts')
    .select('*')
    .in('id', [...assetIds]);
  if (error) throw new BuilderAssetError('approved_asset_lookup', error);

  await mkdir(assetsDirectory, { recursive: true });
  await chmod(assetsDirectory, 0o755);
  const staged = [];
  const stagedFileNames = new Set();
  let index = 0;
  const selectedPageUrls = sourceUrlSet(selectedPages);
  const eligibleAssets = (assets ?? []).filter((candidate) =>
    assetMatchesSelectedPages(candidate, selectedPageUrls, primaryLogoAssetId),
  );
  for (const group of groupApprovedAssetsByContent(eligibleAssets, primaryLogoAssetId)) {
    const asset = group.asset;
    let blob;
    let downloadError;
    try {
      const result = await client.storage
        .from(asset.storage_bucket || artifactBucket)
        .download(asset.storage_path);
      blob = result.data;
      downloadError = result.error;
    } catch (error) {
      throw new BuilderAssetError('approved_asset_download', error, asset.id);
    }
    if (downloadError) {
      throw new BuilderAssetError('approved_asset_download', downloadError, asset.id);
    }
    if (!blob) {
      throw new Error('An approved visual asset could not be loaded into the private workspace.');
    }
    index += 1;
    const metadata = recordValue(asset.metadata);
    const baseFileName = safeFileName(
      typeof metadata.originalFileName === 'string'
        ? metadata.originalFileName
        : asset.storage_path,
      `approved-asset-${index}`,
    );
    const extension = extname(baseFileName);
    const fileStem = basename(baseFileName, extension);
    let fileName = baseFileName;
    let collisionIndex = 2;
    while (stagedFileNames.has(fileName)) {
      fileName = `${fileStem}-${collisionIndex}${extension}`;
      collisionIndex += 1;
    }
    stagedFileNames.add(fileName);
    const outputPath = join(assetsDirectory, fileName);
    await writeFile(outputPath, Buffer.from(await blob.arrayBuffer()));
    await chmod(outputPath, 0o444);
    staged.push(
      approvedAssetDescriptor(
        asset,
        primaryLogoAssetId,
        `public/assets/${fileName}`,
        asset.content_type || blob.type || 'application/octet-stream',
        guidanceByAssetId.get(asset.id),
        {
          duplicateArtifactIds: group.assets
            .map((candidate) => candidate.id)
            .filter((id) => id !== asset.id),
          sourcePageUrls: [
            ...new Set(
              group.assets.flatMap((candidate) => {
                const metadata = recordValue(candidate.metadata);
                return [
                  metadata.pageUrl,
                  ...(Array.isArray(metadata.pageUrls) ? metadata.pageUrls : []),
                ].filter((value) => typeof value === 'string');
              }),
            ),
          ],
          sourceUrls: [
            ...new Set(
              group.assets.flatMap((candidate) => {
                const metadata = recordValue(candidate.metadata);
                return [
                  metadata.sourceUrl,
                  ...(Array.isArray(metadata.sourceUrls) ? metadata.sourceUrls : []),
                ].filter((value) => typeof value === 'string');
              }),
            ),
          ],
        },
      ),
    );
  }
  return staged;
}

function approvedAssetDescriptor(
  asset,
  primaryLogoAssetId,
  relativePath,
  contentType,
  guidance = {},
  provenance = {},
) {
  const metadata = recordValue(asset.metadata);
  const derivedFromAssetId =
    typeof metadata.derivedFromAssetId === 'string' ? metadata.derivedFromAssetId : undefined;
  const isPrimaryLogo = asset.id === primaryLogoAssetId;
  const isLogoFamilyMember =
    Boolean(primaryLogoAssetId) && (isPrimaryLogo || derivedFromAssetId === primaryLogoAssetId);
  const logoAppearance =
    metadata.logoVariant === 'appearance' && typeof metadata.logoAppearance === 'string'
      ? metadata.logoAppearance
      : metadata.logoVariant === 'editable'
        ? 'original'
        : isPrimaryLogo
          ? 'source'
          : undefined;
  return {
    assetId: asset.id,
    relativePath,
    publicPath: `/${relativePath.replace(/^public\//, '')}`,
    contentType,
    ...(typeof asset.label === 'string' && asset.label ? { label: asset.label } : {}),
    ...(typeof guidance.role === 'string' && guidance.role ? { role: guidance.role } : {}),
    ...(typeof guidance.observedDescription === 'string' && guidance.observedDescription
      ? { observedDescription: guidance.observedDescription }
      : {}),
    ...(typeof guidance.safeReuseNote === 'string' && guidance.safeReuseNote
      ? { safeReuseNote: guidance.safeReuseNote }
      : {}),
    ...(Array.isArray(guidance.cautions) && guidance.cautions.length
      ? { cautions: guidance.cautions.filter((item) => typeof item === 'string') }
      : {}),
    ...(Array.isArray(guidance.visibleText) && guidance.visibleText.length
      ? { visibleText: guidance.visibleText.filter((item) => typeof item === 'string') }
      : {}),
    ...(Array.isArray(provenance.sourcePageUrls) && provenance.sourcePageUrls.length
      ? { sourcePageUrls: provenance.sourcePageUrls }
      : {}),
    ...(Array.isArray(provenance.sourceUrls) && provenance.sourceUrls.length
      ? { sourceUrls: provenance.sourceUrls }
      : {}),
    ...(Array.isArray(provenance.duplicateArtifactIds) && provenance.duplicateArtifactIds.length
      ? { duplicateArtifactIds: provenance.duplicateArtifactIds }
      : {}),
    ...(isLogoFamilyMember
      ? {
          logoFamilyPrimaryAssetId: primaryLogoAssetId,
          logoAppearance,
          transparentBackground: metadata.transparentBackground === true,
        }
      : {}),
  };
}

