function cssColourRepresentations(value) {
  const normalized = value.trim().toLowerCase();
  const representations = new Set([normalized]);
  const compactMatch = /^#([0-9a-f])\1([0-9a-f])\2([0-9a-f])\3$/i.exec(normalized);
  if (compactMatch) representations.add(`#${compactMatch[1]}${compactMatch[2]}${compactMatch[3]}`);
  const namedColours = new Map([
    ['#000000', 'black'],
    ['#000080', 'navy'],
    ['#008000', 'green'],
    ['#008080', 'teal'],
    ['#800000', 'maroon'],
    ['#800080', 'purple'],
    ['#808000', 'olive'],
    ['#808080', 'gray'],
    ['#c0c0c0', 'silver'],
    ['#f00', 'red'],
    ['#ff0000', 'red'],
    ['#ffa500', 'orange'],
    ['#fff', 'white'],
    ['#ffffff', 'white'],
  ]);
  if (namedColours.has(normalized)) representations.add(namedColours.get(normalized));
  return [...representations];
}

function brandProblems(manifest, stagedAssets, allFiles) {
  const brandKit = recordValue(recordValue(manifest.data).brandKit);
  if (!brandKit.id) return [];
  const problems = [];
  const primaryLogoId =
    typeof brandKit.primaryLogoAssetId === 'string' ? brandKit.primaryLogoAssetId : '';
  const editableLogoId =
    typeof brandKit.editableLogoAssetId === 'string' ? brandKit.editableLogoAssetId : '';
  const primaryAsset = stagedAssets.find((asset) => asset.assetId === primaryLogoId);
  if (!primaryAsset) {
    problems.push('The approved primary brand logo was not staged for the builder.');
    return problems;
  }
  const outputText = allFiles
    .filter((file) => /\.(html|css)$/i.test(file))
    .map((file) => readFile(file, 'utf8'));
  return Promise.all(outputText).then((contents) => {
    const combined = contents.join('\n').toLowerCase();
    const logoFamilyAssets = stagedAssets.filter(
      (asset) => asset.logoFamilyPrimaryAssetId === primaryLogoId,
    );
    if (
      !logoFamilyAssets.some((asset) =>
        combined.includes(basename(asset.relativePath).toLowerCase()),
      )
    ) {
      problems.push(
        'No approved member of the primary brand logo family is referenced by the generated website.',
      );
    }
    problems.push(...contextualLogoProblems(primaryLogoId, stagedAssets, contents));
    if (editableLogoId) {
      const editableAsset = stagedAssets.find((asset) => asset.assetId === editableLogoId);
      if (!editableAsset) {
        problems.push('The approved editable SVG logo was not staged for the builder.');
      }
    }
    const palette = recordValue(brandKit.palette);
    for (const role of ['primary', 'accent']) {
      const value = palette[role];
      if (
        typeof value === 'string' &&
        /^#[0-9a-f]{6}$/i.test(value) &&
        !cssColourRepresentations(value).some((candidate) => combined.includes(candidate))
      ) {
        problems.push(
          `The reviewed ${role} brand colour is not present in the generated design tokens.`,
        );
      }
    }
    return problems;
  });
}

