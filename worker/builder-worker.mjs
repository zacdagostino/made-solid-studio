function safeRequestPath(rootDirectory, requestPath) {
  const requested = decodeURIComponent(requestPath.split('?')[0] || '/');
  const normalized = requested === '/' ? 'index.html' : requested.replace(/^\/+/, '');
  const resolved = resolve(rootDirectory, normalized);
  if (
    !resolved.startsWith(`${resolve(rootDirectory)}${sep}`) &&
    resolved !== resolve(rootDirectory)
  ) {
    return undefined;
  }
  return resolved;
}

async function startStaticServer(rootDirectory) {
  const server = createServer(async (request, response) => {
    const path = safeRequestPath(rootDirectory, request.url || '/');
    if (!path) {
      response.writeHead(403).end();
      return;
    }
    try {
      const details = await stat(path);
      const target = details.isDirectory() ? join(path, 'index.html') : path;
      const body = await readFile(target);
      response.writeHead(200, {
        'content-type': contentTypeFor(target),
        'cache-control': 'no-store',
      });
      response.end(body);
    } catch {
      response.writeHead(404).end('Not found');
    }
  });
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const address = server.address();
  if (!address || typeof address === 'string')
    throw new Error('Could not create a local quality-check server.');
  return { server, url: `http://127.0.0.1:${address.port}/` };
}

function structuralCheck(htmlFiles) {
  const problems = [];
  for (const file of htmlFiles) {
    const html = file.contents;
    if (!/<title[^>]*>[^<]+<\/title>/i.test(html))
      problems.push(`${file.relativePath} has no title.`);
    if (!/<meta\b[^>]*\bname=["']description["'][^>]*\bcontent=["'][^"']+["']/i.test(html)) {
      problems.push(`${file.relativePath} has no metadata description.`);
    }
    if (!/<main[\s>]/i.test(html)) problems.push(`${file.relativePath} has no main landmark.`);
    const h1Count = html.match(/<h1[\s>]/gi)?.length ?? 0;
    if (h1Count !== 1) {
      problems.push(`${file.relativePath} must contain exactly one H1; found ${h1Count}.`);
    }
    if (
      /<(?:script|img|source|video|audio)\b[^>]*\bsrc=["']https?:\/\//i.test(html) ||
      /<link\b[^>]*\brel=["']stylesheet["'][^>]*\bhref=["']https?:\/\//i.test(html)
    ) {
      problems.push(`${file.relativePath} references a remote file.`);
    }
  }
  return problems;
}

function readableHtmlText(value) {
  return value
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;|&#160;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&(?:quot|ldquo|rdquo);|&#(?:34|8220|8221);/gi, '"')
    .replace(/&(?:apos|lsquo|rsquo);|&#(?:39|8216|8217);/gi, "'")
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/\s+/g, ' ')
    .trim();
}

function placeholderFacingName(value) {
  const name = readableHtmlText(value);
  if (!name) return false;
  if (/^\/[a-z0-9]+(?:[/-][a-z0-9]+)*\/?$/i.test(name)) return true;
  return name
    .split(/\s*[|–—]\s*/)
    .some((part) =>
      /^(?:blank|blank page|unnamed|unnamed page|untitled|untitled page|new page|placeholder|placeholder page|page)$/i.test(
        part.trim(),
      ),
    );
}

function meaningfulPageNamingProblems(htmlFiles) {
  const problems = [];
  for (const file of htmlFiles) {
    const title = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(file.contents)?.[1] ?? '';
    const heading = /<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(file.contents)?.[1] ?? '';
    if (placeholderFacingName(title)) {
      problems.push(
        `${file.relativePath} uses placeholder page title “${readableHtmlText(title)}”.`,
      );
    }
    if (placeholderFacingName(heading)) {
      problems.push(`${file.relativePath} uses placeholder H1 “${readableHtmlText(heading)}”.`);
    }
    const anchors =
      file.contents.match(/<a\b[^>]*\bhref\s*=\s*["'][^"']+["'][^>]*>[\s\S]*?<\/a>/gi) ?? [];
    for (const anchor of anchors) {
      const reference = /\bhref\s*=\s*["']([^"']+)["']/i.exec(anchor)?.[1];
      if (!reference || /^(?:[a-z]+:|\/\/|#)/i.test(reference)) continue;
      const label = readableHtmlText(anchor);
      if (label && placeholderFacingName(label)) {
        problems.push(
          `${file.relativePath} labels internal link ${reference} as placeholder text “${label}”.`,
        );
      }
    }
  }
  return problems;
}

async function mobileNavigationTriggerProblems(htmlFiles, allFiles) {
  const problems = [];
  for (const file of htmlFiles) {
    if (!/\bdata-siteforge-desktop-navigation(?:\s*=|[\s>])/i.test(file.contents)) {
      problems.push(
        `${file.relativePath} must mark its desktop route list with data-siteforge-desktop-navigation.`,
      );
    }
    const triggers =
      file.contents.match(
        /<button\b[^>]*\bdata-siteforge-menu-trigger(?:\s*=\s*["'][^"']*["'])?[^>]*>[\s\S]*?<\/button>/gi,
      ) ?? [];
    if (triggers.length !== 1) {
      problems.push(
        `${file.relativePath} requires exactly one icon-only data-siteforge-menu-trigger button.`,
      );
      continue;
    }
    const trigger = triggers[0];
    const openingTag = trigger.match(/^<button\b[^>]*>/i)?.[0] ?? '';
    const accessibleName = attributeValue(openingTag, 'aria-label');
    if (accessibleName !== 'open navigation' || /\bmenu\b/i.test(accessibleName)) {
      problems.push(
        `${file.relativePath} must name its compact icon trigger “Open navigation” without using “Menu”.`,
      );
    }
    if (attributeValue(openingTag, 'aria-expanded') !== 'false') {
      problems.push(
        `${file.relativePath} must initialise its compact icon trigger with aria-expanded="false".`,
      );
    }
    const renderedText = trigger
      .replace(/^<button\b[^>]*>|<\/button>$/gi, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<[^>]+>/g, '')
      .replace(/&nbsp;|&#160;/gi, ' ')
      .trim();
    if (renderedText) {
      problems.push(
        `${file.relativePath} renders text inside the compact navigation trigger; it must contain only an icon.`,
      );
    }
  }
  for (const file of allFiles.filter((path) => extname(path).toLowerCase() === '.css')) {
    const css = await readFile(file, 'utf8');
    if (/\bcontent\s*:\s*["']\s*(?:menu|navigation|open|close)\s*["']/i.test(css)) {
      problems.push(
        `${basename(file)} uses generated navigation-label text; the compact trigger must remain icon-only.`,
      );
    }
  }
  return problems;
}

