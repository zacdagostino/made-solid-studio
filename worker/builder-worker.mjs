function contextualLogoProblems(primaryLogoId, stagedAssets, contents) {
  const familyAssets = stagedAssets.filter(
    (asset) => asset.logoFamilyPrimaryAssetId === primaryLogoId,
  );
  const appearanceAssets = familyAssets.filter((asset) => asset.logoAppearance);
  if (!primaryLogoId || appearanceAssets.length < 2) return [];
  const assetsByFileName = new Map(
    appearanceAssets.map((asset) => [basename(asset.relativePath).toLowerCase(), asset]),
  );
  const problems = [];
  for (const [pageIndex, content] of contents.entries()) {
    const imageTags = content.match(/<img\b[^>]*>/gi) ?? [];
    for (const tag of imageTags) {
      const source = attributeValue(tag, 'src');
      if (!source) continue;
      const asset = [...assetsByFileName.entries()].find(([fileName]) =>
        source.toLowerCase().includes(fileName),
      )?.[1];
      if (!asset) continue;
      const context = attributeValue(tag, 'data-siteforge-logo-context');
      const declaredAppearance = attributeValue(tag, 'data-siteforge-logo-appearance');
      const actualAppearance = String(asset.logoAppearance).toLowerCase();
      if (!context || !['light', 'dark'].includes(context)) {
        problems.push(
          `Generated page ${pageIndex + 1} uses an approved logo without a valid light/dark context annotation.`,
        );
      }
      if (declaredAppearance !== actualAppearance) {
        problems.push(
          `Generated page ${pageIndex + 1} does not declare the exact staged appearance for an approved logo.`,
        );
      }
      if (context === 'dark' && !['white', 'white-accent'].includes(actualAppearance)) {
        problems.push(
          `Generated page ${pageIndex + 1} uses the ${actualAppearance} logo on a declared dark surface.`,
        );
      }
      if (
        context === 'light' &&
        !['source', 'original', 'black', 'black-accent'].includes(actualAppearance)
      ) {
        problems.push(
          `Generated page ${pageIndex + 1} uses the ${actualAppearance} logo on a declared light surface.`,
        );
      }
    }
  }
  return [...new Set(problems)];
}

