async function sectionRhythmProblems(page, viewport, htmlFile) {
  const evidence = await page.evaluate(() => {
    const headings = [...document.querySelectorAll('[data-siteforge-section-heading]')]
      .map((heading) => {
        const eyebrow = heading.querySelector('[data-siteforge-eyebrow]');
        const title = heading.querySelector('[data-siteforge-title]');
        if (
          !(eyebrow instanceof globalThis.HTMLElement) ||
          !(title instanceof globalThis.HTMLElement)
        )
          return undefined;
        const eyebrowBox = eyebrow.getBoundingClientRect();
        const titleBox = title.getBoundingClientRect();
        return {
          gap: titleBox.top - eyebrowBox.bottom,
          visible: eyebrowBox.height > 0 && titleBox.height > 0,
        };
      })
      .filter(Boolean);
    const sections = [...document.querySelectorAll('[data-siteforge-section-shell]')]
      .filter((section) => section.getAttribute('data-siteforge-section-edge') !== 'flush')
      .map((section) => ({
        paddingBlockEnd: Number.parseFloat(getComputedStyle(section).paddingBlockEnd || '0'),
      }));
    return { headings, sections };
  });
  const problems = [];
  if (evidence.headings.length < 2 || evidence.sections.length < 2) {
    problems.push(
      `${htmlFile.relativePath} does not expose reusable section-rhythm evidence at ${viewport.width}px.`,
    );
    return problems;
  }
  const headingGaps = evidence.headings
    .filter((heading) => heading.visible)
    .map((heading) => heading.gap);
  if (
    headingGaps.length < 2 ||
    Math.min(...headingGaps) < 4 ||
    Math.max(...headingGaps) - Math.min(...headingGaps) > 2
  ) {
    problems.push(
      `${htmlFile.relativePath} has inconsistent eyebrow-to-title spacing at ${viewport.width}px.`,
    );
  }
  const sectionEndSpacing = evidence.sections.map((section) => section.paddingBlockEnd);
  if (
    Math.min(...sectionEndSpacing) < 24 ||
    Math.max(...sectionEndSpacing) - Math.min(...sectionEndSpacing) > 2
  ) {
    problems.push(
      `${htmlFile.relativePath} has inconsistent or cramped section-end spacing at ${viewport.width}px.`,
    );
  }
  return problems;
}

async function responsiveInteractionEvidence(
  page,
  viewport,
  htmlFile,
  enforceLogoAlignment = false,
  enforceLogoReadiness = false,
  enforceLogoSequence = false,
  enforceSectionRhythm = false,
  enforceImmediateNavigation = false,
  enforceFirstViewportHero = false,
) {
  const problems = [];
  await page.evaluate(
    () =>
      new Promise((resolve) => {
        window.scrollTo({ top: 0, left: 0, behavior: 'auto' });
        window.requestAnimationFrame(() => window.requestAnimationFrame(resolve));
      }),
  );
  const renderedImagesReady = () =>
    [...document.images]
      .filter((image) => image.getClientRects().length > 0)
      .every((image) => image.complete && image.naturalWidth > 0 && image.naturalHeight > 0);
  const imagesReady = enforceFirstViewportHero
    ? await page
        .waitForFunction(renderedImagesReady, undefined, { timeout: 2_000 })
        .then(() => true)
        .catch(() => false)
    : true;
  if (enforceFirstViewportHero && !imagesReady) {
    const brokenImages = await page.evaluate(() =>
      [...document.images]
        .filter(
          (image) =>
            image.getClientRects().length > 0 &&
            (!image.complete || image.naturalWidth < 1 || image.naturalHeight < 1),
        )
        .map(
          (image) => image.currentSrc || image.src || image.getAttribute('src') || 'unknown image',
        )
        .slice(0, 4),
    );
    problems.push(
      `${htmlFile.relativePath} has a rendered image that failed to load with positive intrinsic dimensions at ${viewport.width}px: ${brokenImages.join(', ')}.`,
    );
  }
  const overflow = await page.evaluate(() => ({
    documentWidth: document.documentElement.scrollWidth,
    viewportWidth: window.innerWidth,
  }));
  if (overflow.documentWidth > overflow.viewportWidth + 1) {
    problems.push(
      `${htmlFile.relativePath} overflows horizontally at ${viewport.width}px (${overflow.documentWidth}px document width).`,
    );
  }
  if (enforceSectionRhythm) {
    problems.push(...(await sectionRhythmProblems(page, viewport, htmlFile)));
  }
  const desktopNavigation = page.locator('[data-siteforge-desktop-navigation]').first();
  if (viewport.id === 'desktop') {
    if ((await desktopNavigation.count()) === 0 || !(await desktopNavigation.isVisible())) {
      problems.push(`${htmlFile.relativePath} has no visible desktop navigation at 1440px.`);
    }
    const compactTrigger = page.locator('[data-siteforge-menu-trigger]').first();
    if ((await compactTrigger.count()) > 0 && (await compactTrigger.isVisible())) {
      problems.push(`${htmlFile.relativePath} exposes its compact trigger at desktop width.`);
    }
    return { problems };
  }

  if (enforceFirstViewportHero) {
    const heroFit = await page.evaluate(() => {
      const heading = document.querySelector(
        '[data-siteforge-hero-heading], [data-siteforge-hero] h1, main h1',
      );
      const hero =
        heading?.closest('[data-siteforge-hero]') ||
        heading?.closest('section') ||
        heading?.parentElement;
      const primaryAction =
        hero?.querySelector('[data-siteforge-hero-primary-action]') ||
        hero?.querySelector('a[href], button:not([disabled])');
      const headingBox = heading?.getBoundingClientRect();
      const actionBox = primaryAction?.getBoundingClientRect();
      return {
        hasHeading: Boolean(headingBox?.width && headingBox.height),
        hasAction: Boolean(actionBox?.width && actionBox.height),
        headingBottom: headingBox?.bottom,
        actionBottom: actionBox?.bottom,
        headingClipped:
          heading instanceof window.HTMLElement &&
          (heading.scrollWidth > heading.clientWidth + 1 ||
            Boolean(
              headingBox && (headingBox.left < -1 || headingBox.right > window.innerWidth + 1),
            )),
        actionClipped: Boolean(
          actionBox && (actionBox.left < -1 || actionBox.right > window.innerWidth + 1),
        ),
        viewportHeight: window.innerHeight,
      };
    });
    if (!heroFit.hasHeading || heroFit.headingClipped) {
      problems.push(
        `${htmlFile.relativePath} mobile hero heading is missing or horizontally clipped at ${viewport.width}px.`,
      );
    }
    if (
      typeof heroFit.headingBottom !== 'number' ||
      heroFit.headingBottom > heroFit.viewportHeight + 1
    ) {
      problems.push(
        `${htmlFile.relativePath} complete hero heading extends below the first viewport at ${viewport.width}px.`,
      );
    }
    if (
      !heroFit.hasAction ||
      heroFit.actionClipped ||
      typeof heroFit.actionBottom !== 'number' ||
      heroFit.actionBottom > heroFit.viewportHeight + 1
    ) {
      problems.push(
        `${htmlFile.relativePath} primary hero action extends below the first viewport at ${viewport.width}px.`,
      );
    }
  }

  if ((await desktopNavigation.count()) > 0 && (await desktopNavigation.isVisible())) {
    problems.push(
      `${htmlFile.relativePath} exposes desktop navigation in compact mode at ${viewport.width}px.`,
    );
  }

  const trigger = page.locator('[data-siteforge-menu-trigger]').first();
  if ((await trigger.count()) === 0 || !(await trigger.isVisible())) {
    problems.push(
      `${htmlFile.relativePath} has no visible compact navigation trigger at ${viewport.width}px.`,
    );
    return { problems };
  }
  const triggerBox = await trigger.boundingBox();
  const headerBox = await page.locator('header').first().boundingBox();
  if (!triggerBox || triggerBox.width < 44 || triggerBox.height < 44) {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger is smaller than 44×44 at ${viewport.width}px.`,
    );
  }
  if (
    triggerBox &&
    headerBox &&
    triggerBox.x + triggerBox.width / 2 > headerBox.x + headerBox.width / 2
  ) {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger is not at the leading side of the header at ${viewport.width}px.`,
    );
  }
  const compactLogo = page.locator('header [data-siteforge-brand-logo]').first();
  if ((await compactLogo.count()) && (await compactLogo.isVisible())) {
    const alignment = await compactLogo.getAttribute('data-siteforge-compact-logo-alignment');
    if (enforceLogoAlignment && alignment !== 'center' && alignment !== 'flow') {
      problems.push(
        `${htmlFile.relativePath} does not declare whether its compact header logo is viewport-centred or flow-aligned at ${viewport.width}px.`,
      );
    }
    if (alignment === 'center') {
      const logoBox = await compactLogo.boundingBox();
      if (logoBox && Math.abs(logoBox.x + logoBox.width / 2 - viewport.width / 2) > 2) {
        problems.push(
          `${htmlFile.relativePath} declares a centred compact logo but is offset from the viewport centre at ${viewport.width}px.`,
        );
      }
    }
    if (enforceLogoReadiness) {
      const logoReady = await compactLogo.evaluate((element) => {
        const image = element.matches('img') ? element : element.querySelector('img');
        return (
          image instanceof globalThis.HTMLImageElement && image.complete && image.naturalWidth > 0
        );
      });
      if (!logoReady) {
        problems.push(
          `${htmlFile.relativePath} header logo is not decoded and ready on first render at ${viewport.width}px.`,
        );
      }
    }
  }
  const initialName = await trigger.getAttribute('aria-label');
  if (initialName !== 'Open navigation') {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger is not named “Open navigation” while closed.`,
    );
  }

  const openAttempt = await activateCompactNavigationTrigger(trigger);
  if (!openAttempt.activated) {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger could not be activated with a pointer after ${openAttempt.attempts} attempts at ${viewport.width}px: ${openAttempt.detail}`,
    );
    return { problems };
  }
  await page.waitForFunction(
    () =>
      document.querySelector('[data-siteforge-menu-trigger]')?.getAttribute('aria-expanded') ===
      'true',
    undefined,
    { timeout: 2_000 },
  );
  const openTrigger = page.locator('[data-siteforge-menu-trigger]').first();
  if ((await openTrigger.getAttribute('aria-label')) !== 'Close navigation') {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger is not named “Close navigation” while open.`,
    );
  }
  const dialog = page.locator('[data-siteforge-navigation-dialog]').first();
  if ((await dialog.count()) === 0 || !(await dialog.isVisible())) {
    problems.push(
      `${htmlFile.relativePath} does not expose a visible data-siteforge-navigation-dialog at ${viewport.width}px.`,
    );
  } else {
    const navigationReady = await dialog
      .waitFor({ state: 'visible', timeout: 2_000 })
      .then(() =>
        page.waitForFunction(
          () =>
            document
              .querySelector('[data-siteforge-navigation-dialog]')
              ?.classList.contains('is-sf-navigation-ready') === true,
          undefined,
          { timeout: 2_000 },
        ),
      )
      .then(() => true)
      .catch(() => false);
    if (!navigationReady) {
      problems.push(
        `${htmlFile.relativePath} compact-navigation content did not become ready at ${viewport.width}px.`,
      );
    }
    const navigationPacing = await dialog.evaluate((surface) => {
      const milliseconds = (value) => {
        const trimmed = value.trim();
        const parsed = Number.parseFloat(trimmed);
        if (!Number.isFinite(parsed)) return 0;
        return trimmed.endsWith('ms') ? parsed : parsed * 1_000;
      };
      const items = [...surface.querySelectorAll('[data-sf-navigation-item]')];
      const delayFor = (element) =>
        element
          ? Math.max(...getComputedStyle(element).transitionDelay.split(',').map(milliseconds))
          : undefined;
      const logo = items.find((item) => item.matches('[data-siteforge-navigation-logo]'));
      const firstRoute = items.find(
        (item) => item.matches('a[href]') || item.querySelector('a[href]'),
      );
      return {
        logoDelay: delayFor(logo),
        firstRouteDelay: delayFor(firstRoute),
        maximumDelay: items.length ? Math.max(...items.map((item) => delayFor(item) ?? 0)) : 0,
        animationName: getComputedStyle(surface).animationName,
        scrollbarWidth: getComputedStyle(surface).scrollbarWidth,
        closedTranslate: getComputedStyle(surface).getPropertyValue(
          '--sf-navigation-closed-translate',
        ),
        direction: getComputedStyle(surface).direction,
      };
    });
    if ((navigationPacing.logoDelay ?? Number.POSITIVE_INFINITY) > 16) {
      problems.push(
        `${htmlFile.relativePath} compact-navigation logo does not begin revealing immediately at ${viewport.width}px.`,
      );
    }
    if (
      (navigationPacing.firstRouteDelay ?? Number.POSITIVE_INFINITY) >
      (enforceImmediateNavigation ? 16 : 60)
    ) {
      problems.push(
        `${htmlFile.relativePath} first compact-navigation route waits too long to begin revealing at ${viewport.width}px.`,
      );
    }
    if (navigationPacing.maximumDelay > (enforceImmediateNavigation ? 16 : 250)) {
      problems.push(
        `${htmlFile.relativePath} compact-navigation item sequence is delayed too long at ${viewport.width}px.`,
      );
    }
    if (enforceImmediateNavigation && navigationPacing.animationName !== 'none') {
      problems.push(
        `${htmlFile.relativePath} compact-navigation surface has a competing generated animation at ${viewport.width}px.`,
      );
    }
    if (enforceImmediateNavigation && navigationPacing.scrollbarWidth !== 'none') {
      problems.push(
        `${htmlFile.relativePath} compact-navigation surface exposes nested scrollbar chrome at ${viewport.width}px.`,
      );
    }
    if (
      enforceImmediateNavigation &&
      navigationPacing.direction !== 'rtl' &&
      navigationPacing.closedTranslate.trim() !== '-100%'
    ) {
      problems.push(
        `${htmlFile.relativePath} compact navigation is not configured to enter from the left at ${viewport.width}px.`,
      );
    }
    const navigationItemsVisible = await page
      .waitForFunction(
        () => {
          const surface = document.querySelector('[data-siteforge-navigation-dialog]');
          const elements = surface?.querySelectorAll('[data-sf-navigation-item]') ?? [];
          return (
            elements.length > 0 &&
            [...elements].every((element) => {
              const styles = getComputedStyle(element);
              const bounds = element.getBoundingClientRect();
              return (
                styles.visibility !== 'hidden' &&
                styles.display !== 'none' &&
                Number.parseFloat(styles.opacity || '1') >= 0.95 &&
                bounds.width > 0 &&
                bounds.height > 0
              );
            })
          );
        },
        undefined,
        { timeout: 2_000 },
      )
      .then(() => true)
      .catch(() => false);
    if (!navigationItemsVisible) {
      problems.push(
        `${htmlFile.relativePath} compact-navigation routes are not visibly stable after opening at ${viewport.width}px.`,
      );
    }
    const dialogBox = await dialog.boundingBox();
    if (!dialogBox || dialogBox.y > 1 || dialogBox.height < viewport.height - 1) {
      problems.push(
        `${htmlFile.relativePath} compact navigation does not fill the viewport height at ${viewport.width}px.`,
      );
    }
    if (
      enforceImmediateNavigation &&
      navigationPacing.direction !== 'rtl' &&
      dialogBox &&
      dialogBox.x > 1
    ) {
      problems.push(
        `${htmlFile.relativePath} compact navigation is not anchored to the left edge at ${viewport.width}px.`,
      );
    }
    const backdrop = page.locator('[data-siteforge-navigation-backdrop]').first();
    const backdropBox =
      (await backdrop.count()) > 0 && (await backdrop.isVisible())
        ? await backdrop.boundingBox()
        : undefined;
    if (
      !backdropBox ||
      backdropBox.x > 1 ||
      backdropBox.y > 1 ||
      backdropBox.width < viewport.width - 1 ||
      backdropBox.height < viewport.height - 1
    ) {
      problems.push(
        `${htmlFile.relativePath} compact-navigation backdrop does not cover the viewport at ${viewport.width}px.`,
      );
    }
    if (enforceLogoReadiness) {
      const navigationLogo = dialog.locator('[data-siteforge-navigation-logo]').first();
      const navigationLogoReady =
        (await navigationLogo.count()) > 0 &&
        (await navigationLogo.evaluate((element) => {
          const image = element.matches('img') ? element : element.querySelector('img');
          if (image instanceof globalThis.HTMLImageElement) {
            return image.complete && image.naturalWidth > 0;
          }
          return element.matches('svg') || Boolean(element.querySelector('svg'));
        }));
      if (!navigationLogoReady) {
        problems.push(
          `${htmlFile.relativePath} compact-navigation logo was not already decoded when the drawer first opened at ${viewport.width}px.`,
        );
      }
      if (enforceLogoSequence && (await navigationLogo.count()) > 0) {
        const logoLeadsSequence = await navigationLogo.evaluate((element) => {
          const firstItem = element
            .closest('[data-siteforge-navigation-dialog]')
            ?.querySelector('[data-sf-navigation-item]');
          return firstItem === element || Boolean(firstItem?.contains(element));
        });
        if (!logoLeadsSequence) {
          problems.push(
            `${htmlFile.relativePath} compact-navigation routes can animate before its approved logo at ${viewport.width}px.`,
          );
        }
      }
    }
    const closeControl = dialog.locator('[data-siteforge-navigation-close]').first();
    const closeBox =
      (await closeControl.count()) && (await closeControl.isVisible())
        ? await closeControl.boundingBox()
        : undefined;
    if (!closeBox || closeBox.width < 44 || closeBox.height < 44) {
      problems.push(
        `${htmlFile.relativePath} has no visible 44×44 compact navigation close control at ${viewport.width}px.`,
      );
    }
    const activeInsideDialog = await page.evaluate(() => {
      const surface = document.querySelector('[data-siteforge-navigation-dialog]');
      return Boolean(surface && surface.contains(document.activeElement));
    });
    if (!activeInsideDialog) {
      problems.push(
        `${htmlFile.relativePath} does not move focus into compact navigation at ${viewport.width}px.`,
      );
    }
    const links = await dialog.locator('a[href]').evaluateAll((elements) =>
      elements
        .filter((element) => {
          const styles = getComputedStyle(element);
          const bounds = element.getBoundingClientRect();
          return styles.visibility !== 'hidden' && styles.display !== 'none' && bounds.height > 0;
        })
        .map((element) => {
          const bounds = element.getBoundingClientRect();
          return { top: bounds.top, left: bounds.left, width: bounds.width, height: bounds.height };
        }),
    );
    if (
      links.some((link, index) => {
        const previous = links[index - 1];
        return previous ? link.top < previous.top + previous.height - 1 : false;
      })
    ) {
      problems.push(
        `${htmlFile.relativePath} compact navigation links do not form one vertical route sequence at ${viewport.width}px.`,
      );
    }
  }

  await page.keyboard.press('Escape');
  await page.waitForFunction(
    () =>
      document.querySelector('[data-siteforge-menu-trigger]')?.getAttribute('aria-expanded') ===
      'false',
    undefined,
    { timeout: 2_000 },
  );
  if (enforceImmediateNavigation && (await dialog.count()) === 0) {
    problems.push(
      `${htmlFile.relativePath} unmounts compact navigation before its exit motion can complete at ${viewport.width}px.`,
    );
  }
  const focusRestored = await page
    .waitForFunction(
      () => document.activeElement === document.querySelector('[data-siteforge-menu-trigger]'),
      undefined,
      { timeout: 750 },
    )
    .then(() => true)
    .catch(() => false);
  if (!focusRestored) {
    problems.push(
      `${htmlFile.relativePath} does not restore focus to the compact trigger after Escape at ${viewport.width}px.`,
    );
  }
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const reducedMotionAttempt = await activateCompactNavigationTrigger(openTrigger);
  if (!reducedMotionAttempt.activated) {
    problems.push(
      `${htmlFile.relativePath} compact navigation trigger could not be activated with reduced motion after ${reducedMotionAttempt.attempts} attempts at ${viewport.width}px: ${reducedMotionAttempt.detail}`,
    );
    await page.emulateMedia({ reducedMotion: 'no-preference' });
    return { problems };
  }
  await page.waitForFunction(
    () =>
      document.querySelector('[data-siteforge-menu-trigger]')?.getAttribute('aria-expanded') ===
      'true',
    undefined,
    { timeout: 2_000 },
  );
  await page.keyboard.press('Escape');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  return { problems };
}

