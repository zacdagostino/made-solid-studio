function semanticEvidenceStrings(item) {
  const structured = recordValue(recordValue(item).structuredContent);
  const testimonial = recordValue(structured.testimonial);
  const table = recordValue(structured.table);
  const itemRows = Array.isArray(structured.items) ? structured.items : [];
  const faqs = Array.isArray(structured.faqs) ? structured.faqs : [];
  const values = [];
  if (structured.kind === 'testimonial') {
    values.push(testimonial.quote, testimonial.person, testimonial.role, testimonial.organisation);
  } else if (structured.kind === 'table') {
    values.push(
      table.caption,
      ...(Array.isArray(table.columns) ? table.columns : []),
      ...(Array.isArray(table.rows) ? table.rows.flat() : []),
      ...(Array.isArray(table.footnotes) ? table.footnotes : []),
    );
  } else {
    values.push(structured.heading, structured.body);
    for (const row of itemRows) {
      const entry = recordValue(row);
      values.push(entry.label, entry.value, entry.detail);
    }
    for (const faq of faqs) {
      const entry = recordValue(faq);
      values.push(entry.question, entry.answer);
    }
  }
  return [
    ...new Set(
      values
        .filter((value) => typeof value === 'string')
        .map(normaliseSemanticText)
        .filter(Boolean),
    ),
  ];
}

