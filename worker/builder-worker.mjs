function generatedReferenceCandidates(reference, fromPath) {
  const cleanReference = reference.split(/[?#]/, 1)[0];
  let decodedReference;
  try {
    decodedReference = decodeURIComponent(cleanReference);
  } catch {
    return [];
  }
  const resolved = decodedReference.startsWith('/')
    ? relative('/', resolve('/', decodedReference))
    : relative('/', resolve('/', dirname(fromPath), decodedReference));
  const normalized = resolved
    .split(sep)
    .join('/')
    .replace(/^\.\/+/, '');
  if (!normalized || normalized === '.') return ['index.html'];
  if (normalized.startsWith('../')) return [];
  if (extname(normalized)) return [normalized];
  return [
    normalized,
    `${normalized.replace(/\/+$/, '')}/index.html`,
    `${normalized.replace(/\/+$/, '')}.html`,
  ].filter((path, index, paths) => paths.indexOf(path) === index);
}

function missingLocalRuntimeFiles(htmlFiles, allFiles, outputDirectory) {
  const generatedPaths = new Set(
    allFiles.map((file) => relative(outputDirectory, file).split(sep).join('/')),
  );
  const problems = [];
  for (const file of htmlFiles) {
    const tags = file.contents.match(/<(?:link|script)\b[^>]*>/gi) ?? [];
    for (const tag of tags) {
      const isStylesheet = /^<link\b/i.test(tag) && /\brel\s*=\s*["']stylesheet["']/i.test(tag);
      const isScript = /^<script\b/i.test(tag);
      if (!isStylesheet && !isScript) continue;
      const reference = isStylesheet
        ? /\bhref\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1]
        : /\bsrc\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1];
      if (!reference || /^(?:[a-z]+:|\/\/|#)/i.test(reference)) continue;
      const candidates = generatedReferenceCandidates(reference, file.relativePath);
      if (!candidates.some((candidate) => generatedPaths.has(candidate))) {
        problems.push(`${file.relativePath} references missing local file ${reference}.`);
      }
    }
  }
  return problems;
}

function missingInternalNavigationTargets(htmlFiles, allFiles, outputDirectory) {
  const generatedPaths = new Set(
    allFiles.map((file) => relative(outputDirectory, file).split(sep).join('/')),
  );
  const problems = [];
  for (const file of htmlFiles) {
    const anchors = file.contents.match(/<a\b[^>]*\bhref\s*=\s*["'][^"']+["'][^>]*>/gi) ?? [];
    for (const anchor of anchors) {
      const reference = /\bhref\s*=\s*["']([^"']+)["']/i.exec(anchor)?.[1];
      if (!reference || /^(?:[a-z]+:|\/\/|#)/i.test(reference)) continue;
      const candidates = generatedReferenceCandidates(reference, file.relativePath);
      if (!candidates.length) {
        problems.push(`${file.relativePath} has an invalid internal link ${reference}.`);
        continue;
      }
      const target = candidates.find(
        (candidate) =>
          generatedPaths.has(candidate) && extname(candidate).toLowerCase() === '.html',
      );
      if (!target) {
        problems.push(
          `${file.relativePath} links to ${reference}, which does not resolve to a generated route.`,
        );
      }
    }
  }
  return problems;
}

function unreachableSelectedPageProblems(htmlFiles, selectedPages = []) {
  const generatedPaths = new Set(htmlFiles.map((file) => file.relativePath));
  if (!generatedPaths.has('index.html') || generatedPaths.size <= 1) return [];
  const linksByPage = new Map();
  for (const file of htmlFiles) {
    const links = new Set();
    const anchors = file.contents.match(/<a\b[^>]*\bhref\s*=\s*["'][^"']+["'][^>]*>/gi) ?? [];
    for (const anchor of anchors) {
      const reference = /\bhref\s*=\s*["']([^"']+)["']/i.exec(anchor)?.[1];
      if (!reference || /^(?:[a-z]+:|\/\/|#)/i.test(reference)) continue;
      try {
        const target = generatedReferenceCandidates(reference, file.relativePath).find(
          (candidate) => generatedPaths.has(candidate),
        );
        if (target) links.add(target);
      } catch {
        // Invalid links are reported by missingInternalNavigationTargets.
      }
    }
    linksByPage.set(file.relativePath, links);
  }
  const visited = new Set(['index.html']);
  const pending = ['index.html'];
  while (pending.length) {
    const page = pending.shift();
    for (const target of linksByPage.get(page) ?? []) {
      if (visited.has(target)) continue;
      visited.add(target);
      pending.push(target);
    }
  }
  const navigationExemptPaths = new Set(
    selectedPages
      .filter((page) => page.disposition === 'redirect' || page.disposition === 'workflow_state')
      .map((page) => page.outputPath),
  );
  return [...generatedPaths]
    .filter((path) => !visited.has(path) && !navigationExemptPaths.has(path))
    .map((path) => `${path} cannot be reached by following internal links from index.html.`);
}

function inconsistentHeaderNavigationProblems(htmlFiles) {
  const signatures = htmlFiles.map((file) => {
    const header = /<header\b[\s\S]*?<\/header>/i.exec(file.contents)?.[0] ?? '';
    const links = [
      ...header.matchAll(/<a\b[^>]*\bhref\s*=\s*["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/gi),
    ]
      .map((match) => ({
        href: match[1],
        text: match[2]
          .replace(/<[^>]+>/g, ' ')
          .replace(/\s+/g, ' ')
          .trim()
          .toLowerCase(),
      }))
      .filter((link) => link.text);
    return {
      relativePath: file.relativePath,
      signature: JSON.stringify(links),
      links,
    };
  });
  const signatureCounts = new Map();
  for (const entry of signatures) {
    signatureCounts.set(entry.signature, (signatureCounts.get(entry.signature) ?? 0) + 1);
  }
  const canonical = [...signatureCounts.entries()].sort(
    ([leftSignature, leftCount], [rightSignature, rightCount]) =>
      rightCount - leftCount || leftSignature.localeCompare(rightSignature),
  )[0]?.[0];
  if (!canonical) return [];
  return signatures
    .filter((entry) => entry.signature !== canonical)
    .map(
      (entry) =>
        `${entry.relativePath} uses different primary header destinations from the rest of the generated site.`,
    );
}

function multiPageHeaderRouteNavigationProblems(htmlFiles) {
  const generatedPaths = new Set(htmlFiles.map((file) => file.relativePath));
  if (!generatedPaths.has('index.html') || generatedPaths.size <= 1) return [];
  const problems = [];
  for (const file of htmlFiles) {
    const header = /<header\b[\s\S]*?<\/header>/i.exec(file.contents)?.[0] ?? '';
    const references = [...header.matchAll(/<a\b[^>]*\bhref\s*=\s*["']([^"']+)["'][^>]*>/gi)].map(
      (match) => match[1],
    );
    const fragmentLinks = references.filter((reference) => /^(?:#|\/#)/.test(reference));
    if (fragmentLinks.length) {
      problems.push(
        `${file.relativePath} uses homepage section shortcuts in its primary header instead of generated page routes.`,
      );
    }
    const hasNonHomeRoute = references.some((reference) => {
      if (/^(?:[a-z]+:|\/\/|#)/i.test(reference)) return false;
      return generatedReferenceCandidates(reference, file.relativePath).some(
        (candidate) => candidate !== 'index.html' && generatedPaths.has(candidate),
      );
    });
    if (!hasNonHomeRoute) {
      problems.push(
        `${file.relativePath} primary header does not link to any generated non-home page.`,
      );
    }
  }
  return problems;
}

function sourceUrlMarker(html) {
  const tags = html.match(/<meta\b[^>]*>/gi) ?? [];
  for (const tag of tags) {
    const name = /\bname\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1];
    const content = /\bcontent\s*=\s*["']([^"']+)["']/i.exec(tag)?.[1];
    if (name?.toLowerCase() === 'siteforge-source-url' && content) return content;
  }
  return undefined;
}

function selectedPageCoverageCheck(
  manifest,
  htmlFiles,
  buildMode,
  targetSourceUrl,
  targetSourceUrls = [],
) {
  const selectedPages = sourcePagePlan(
    Array.isArray(recordValue(manifest.data).selectedPages)
      ? recordValue(manifest.data).selectedPages
      : [],
  );
  const targetSourceUrlSet = new Set(targetSourceUrls);
  const scopedPages =
    buildMode === 'homepage_test'
      ? selectedPages.filter((page) => page.outputPath === 'index.html').slice(0, 1)
      : buildMode === 'page_test'
        ? targetSourceUrlSet.size
          ? selectedPages.filter((page) => targetSourceUrlSet.has(page.sourceUrl))
          : selectedPages.filter((page) => page.sourceUrl === targetSourceUrl).slice(0, 1)
        : selectedPages;
  const generatedByPath = new Map(htmlFiles.map((file) => [file.relativePath, file]));
  const problems = [];
  for (const page of scopedPages) {
    const output = generatedByPath.get(page.outputPath);
    if (!output) {
      problems.push(`${page.outputPath} is missing for selected source ${page.sourceUrl}.`);
      continue;
    }
    const marker = sourceUrlMarker(output.contents);
    if (!marker) {
      problems.push(`${page.outputPath} has no selected-source provenance marker.`);
      continue;
    }
    try {
      if (normaliseSourceUrl(marker) !== page.sourceUrl) {
        problems.push(`${page.outputPath} is mapped to the wrong selected source page.`);
      }
    } catch {
      problems.push(`${page.outputPath} has an invalid selected-source provenance marker.`);
    }
  }
  return { expectedPageCount: scopedPages.length, problems };
}

