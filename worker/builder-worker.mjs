async function prepareWorkspace(client, run, manifest, workerId, diagnostics) {
  await updateProgress(client, run, workerId, {
    progress_phase: 'preparing_workspace',
    progress_detail: 'Creating a clean private website workspace.',
    total_items: 7,
    completed_items: 0,
  });
  const runDirectory = await mkdtemp(join(tmpdir(), 'siteforge-builder-'));
  const siteDirectory = join(runDirectory, 'website');
  const inputDirectory = join(runDirectory, 'input');
  try {
    await stat(join(templateDependenciesDirectory, 'next', 'package.json'));
  } catch {
    throw new Error(
      'The locked Next.js builder dependencies are unavailable. Run npm ci --prefix worker/builder-template in the protected worker image.',
    );
  }
  await cp(templateDirectory, siteDirectory, {
    recursive: true,
    filter: (source) =>
      !['node_modules', '.next', compiledOutputDirectoryName].includes(basename(source)),
  });
  await symlink(templateDependenciesDirectory, join(siteDirectory, 'node_modules'), 'dir');
  await mkdir(inputDirectory, { recursive: true });
  await runDiagnosticCommand(diagnostics, 'workspace_initialisation', 'git', ['init', '--quiet'], {
    cwd: runDirectory,
    env: process.env,
  });
  const { data: agentPackage, error: packageError } = await client
    .from('agent_packages')
    .select(
      'id, version, status, builder_contract_version, foundation_version, contract_addendum, instructions_addendum, capability_assessment',
    )
    .eq('id', run.agent_package_id)
    .eq('organization_id', run.organization_id)
    .single();
  if (packageError || !agentPackage) {
    throw new Error('The agent package pinned to this private build could not be loaded.');
  }
  if (agentPackage.foundation_version !== run.template_version) {
    throw new Error('The agent package foundation no longer matches this immutable private build.');
  }
  if (run.template_version !== builderFoundationVersion) {
    throw new Error('This private build uses a retired builder foundation.');
  }
  if (run.build_mode === 'full_site' && agentPackage.status !== 'published') {
    throw new Error('A complete prospect build must use a published agent package.');
  }

  const buildMode =
    run.build_mode === 'full_site'
      ? 'full_site'
      : run.build_mode === 'site_test'
        ? 'site_test'
        : run.build_mode === 'page_test'
          ? 'page_test'
          : 'homepage_test';
  const targetSourceUrl =
    typeof run.target_source_url === 'string' && run.target_source_url
      ? normaliseSourceUrl(run.target_source_url)
      : undefined;
  const targetSourceUrls = Array.isArray(run.target_source_urls)
    ? [...new Set(run.target_source_urls)]
        .filter((sourceUrl) => typeof sourceUrl === 'string' && Boolean(sourceUrl))
        .map((sourceUrl) => normaliseSourceUrl(sourceUrl))
    : [];
  let sourceRun = run;
  if (run.parent_builder_run_id) {
    const { data: parentRun, error: parentError } = await client
      .from('builder_runs')
      .select('id, organization_id, business_id, build_manifest_id, build_mode, target_source_url')
      .eq('id', run.parent_builder_run_id)
      .maybeSingle();
    if (
      parentError ||
      !parentRun ||
      parentRun.organization_id !== run.organization_id ||
      parentRun.business_id !== run.business_id ||
      (run.build_mode === 'site_test'
        ? !['homepage_test', 'page_test', 'site_test', 'full_site'].includes(parentRun.build_mode)
        : !['homepage_test', 'page_test'].includes(parentRun.build_mode) ||
          (parentRun.target_source_url
            ? normaliseSourceUrl(parentRun.target_source_url)
            : undefined) !== targetSourceUrl)
    ) {
      throw new BuilderCheckpointError(
        'The selected homepage test source is no longer available.',
        {
          context: { operation: 'homepage_test_lookup' },
        },
      );
    }
    if (parentRun.build_manifest_id !== manifest.id) {
      const { data: parentManifest, error: parentManifestError } = await client
        .from('build_manifests')
        .select('crawl_run_id, research_packet_id')
        .eq('id', parentRun.build_manifest_id)
        .eq('organization_id', run.organization_id)
        .eq('business_id', run.business_id)
        .maybeSingle();
      if (
        parentManifestError ||
        !parentManifest ||
        !revisionManifestCompatible(manifest, {
          id: parentRun.build_manifest_id,
          ...parentManifest,
        })
      ) {
        throw new BuilderCheckpointError(
          'The selected private page is based on different research and cannot be rebased onto this manifest.',
          {
            context: { operation: 'revision_manifest_compatibility' },
          },
        );
      }
    }
    sourceRun = parentRun;
  }
  // A full-site build may restore a completed test as its design baseline, but it
  // must still receive the complete manifest and generate every selected page.
  // Only an explicitly page-scoped test/refinement uses the revision contract.
  const scopedRevision =
    !['full_site', 'site_test'].includes(run.build_mode) && sourceRun.id !== run.id;
  let manifestText;
  let manifestPath;
  let stagedSourcePages;
  let revisionScope;
  let stagedAssets;
  let projectedManifestData = recordValue(manifest.data);
  if (scopedRevision) {
    revisionScope = await stageRevisionScope(
      manifest,
      inputDirectory,
      buildMode,
      targetSourceUrl,
      sourceRun,
    );
    manifestText = revisionScope.scopeText;
    manifestPath = revisionScope.scopePath;
    stagedSourcePages = [revisionScope.selectedPage];
    stagedAssets = await stageApprovedAssets(client, manifest, siteDirectory, stagedSourcePages);
  } else {
    manifestPath = join(inputDirectory, 'manifest.json');
    stagedSourcePages = await stageSelectedPageContent(
      client,
      manifest,
      inputDirectory,
      buildMode,
      targetSourceUrl,
      targetSourceUrls,
    );
    stagedAssets = await stageApprovedAssets(client, manifest, siteDirectory, stagedSourcePages);
    projectedManifestData = projectManifestData(
      manifest.data,
      stagedSourcePages,
      stagedAssets,
      buildMode,
    );
    manifestText = JSON.stringify(projectedManifestData, null, 2);
    await writeFile(manifestPath, manifestText);
    await chmod(manifestPath, 0o444);
  }
  const contextSummary = buildContextSummary({
    fullData: manifest.data,
    projectedData: scopedRevision ? recordValue(JSON.parse(manifestText)) : projectedManifestData,
    selectedPages: stagedSourcePages,
    stagedAssets,
    buildMode,
    scopedRevision,
  });
  const contextSummaryPath = join(inputDirectory, 'build-context.json');
  await writeFile(contextSummaryPath, JSON.stringify(contextSummary, null, 2));
  await chmod(contextSummaryPath, 0o444);
  const templateSourceHashes = await sourceFileHashes(siteDirectory);
  const checkpoint = await restoreSourceCheckpoint(
    client,
    run,
    join(siteDirectory, 'src'),
    sourceRun,
  );
  // A checkpoint records generated source, not an immutable copy of the worker
  // foundation. Older checkpoints may contain a formerly locked runtime file,
  // so always reapply the current protected foundation before hashing or
  // verification. This keeps resume useful without allowing saved source to
  // pin a stale or broken runtime.
  await refreshLockedFoundation(siteDirectory);
  await writeFile(
    join(inputDirectory, 'approved-assets.json'),
    JSON.stringify(stagedAssets, null, 2),
  );
  await chmod(join(inputDirectory, 'approved-assets.json'), 0o444);
  const initialSourceHashes = await sourceFileHashes(siteDirectory);
  const rebasedToCurrentManifest = revisionScope?.rebasedToCurrentManifest === true;

  const lockedFiles = await Promise.all(
    lockedFoundationPaths.map(async (relativePath) => {
      const path = join(siteDirectory, relativePath);
      const source = await readFile(path);
      await chmod(path, 0o444);
      return [relativePath, sha256(source)];
    }),
  );
  await updateProgress(client, run, workerId, {
    progress_phase: 'preparing_workspace',
    progress_detail: checkpoint.restored
      ? checkpoint.restoredFromLegacyDrafts
        ? `Restored ${checkpoint.fileCount} saved draft file${checkpoint.fileCount === 1 ? '' : 's'} into the isolated workspace${rebasedToCurrentManifest ? ' for a current-manifest asset rebase' : scopedRevision ? ' for a scoped refinement' : ''}.`
        : `Restored a private source checkpoint with ${checkpoint.fileCount} file${checkpoint.fileCount === 1 ? '' : 's'} into the isolated workspace${rebasedToCurrentManifest ? ' for a current-manifest asset rebase' : scopedRevision ? ' for a scoped refinement' : ''}.`
      : `Manifest, ${stagedSourcePages.length} selected page source${stagedSourcePages.length === 1 ? '' : 's'}, and ${stagedAssets.length} approved asset${stagedAssets.length === 1 ? '' : 's'} staged in the isolated workspace.`,
    total_items: 7,
    completed_items: 1,
    input_hash: sha256(manifestText),
  });
  return {
    runDirectory,
    siteDirectory,
    manifestPath,
    lockedFiles,
    stagedAssets,
    stagedSourcePages,
    buildMode,
    targetSourceUrl,
    targetSourceUrls,
    templateSourceHashes,
    initialSourceHashes,
    draftHashes: sourceRun.id === run.id ? checkpoint.draftHashes : new Map(),
    draftFailures: new Map(),
    checkpointHash: checkpoint.checkpointHash,
    checkpointState: checkpoint.checkpointState,
    checkpointFailure: undefined,
    draftOutputHashes: new Map(),
    draftPublished: false,
    restoredCheckpoint: checkpoint.restored,
    restoredFromLegacyDrafts: checkpoint.restoredFromLegacyDrafts,
    restoredCheckpointFileCount: checkpoint.fileCount ?? 0,
    restoredHomepageTest: sourceRun.id !== run.id,
    scopedRevision,
    rebasedToCurrentManifest,
    revisionScopePath: revisionScope?.scopePath,
    contextSummaryPath,
    contextSummary,
    allowedSourcePaths: revisionScope?.allowedSourcePaths ?? [],
    allowedSourcePrefixes: revisionScope?.allowedSourcePrefixes ?? [],
    agentPackage,
  };
}

async function assertLockedFiles(siteDirectory, lockedFiles) {
  for (const [relativePath, originalHash] of lockedFiles) {
    const current = await readFile(join(siteDirectory, relativePath));
    if (sha256(current) !== originalHash) {
      throw new Error('The builder changed a locked workspace foundation file.');
    }
  }
}

async function assertScopedRevisionFiles(workspace) {
  if (!workspace.scopedRevision) return;
  const allowed = new Set(workspace.allowedSourcePaths);
  const allowedPrefixes = workspace.allowedSourcePrefixes ?? [];
  const currentHashes = await sourceFileHashes(workspace.siteDirectory);
  const paths = new Set([...workspace.initialSourceHashes.keys(), ...currentHashes.keys()]);
  const outOfScopeChanges = [...paths]
    .filter((path) => workspace.initialSourceHashes.get(path) !== currentHashes.get(path))
    .filter(
      (path) => !allowed.has(path) && !allowedPrefixes.some((prefix) => path.startsWith(prefix)),
    );
  if (outOfScopeChanges.length) {
    throw new Error(
      `The scoped refinement changed files outside its allowed page scope: ${outOfScopeChanges
        .slice(0, 5)
        .join(', ')}.`,
    );
  }
}

